        source = path.read_text()
        # These words are also excluded from comments to keep this check simple.
        if re.search(r"\b(sorry|admit|axiom|unsafe)\b|implemented_by", source):
            raise SystemExit(f"Unapproved proof construct: {path.relative_to(ROOT)}")

